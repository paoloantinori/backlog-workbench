// Reproducible build for the shipped reader artifacts.
//
//   cd reader && npm ci && bun run build
//
// Emits, from the exact versions pinned in package-lock.json:
//   ../plugin/reader.cjs             self-contained CommonJS bundle (node builtins only)
//   ../plugin/THIRD_PARTY_NOTICES.md full license notices for everything compiled in
//
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync } from 'node:fs'
import { basename, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { assertBundledRequires } from './bundle-audit.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const lock = JSON.parse(readFileSync(join(here, 'package-lock.json'), 'utf8'))
const provenance = JSON.parse(readFileSync(join(here, 'vendor/provenance.json'), 'utf8'))
const defaultSafe = join(here, 'node_modules/js-yaml/lib/js-yaml/schema/default_safe.js')

// gray-matter 4.0.3 parses YAML only through js-yaml safeLoad/safeDump
// (gray-matter/lib/engines.js). js-yaml's default_full schema is reachable only through
// yaml.load/yaml.dump, which nothing in this reader calls, and its type/js/function.js
// resolves the esprima package from node_modules at module initialization. The plugin
// below replaces that one schema module with an alias of default_safe, so the bundle
// keeps official safeLoad behavior and performs no external module resolution at init.
const dropUnsafeYamlSchema = {
  name: 'drop-unsafe-yaml-schema',
  setup(build) {
    build.onResolve({ filter: /schema[/\\]default_full$/ }, args =>
      args.namespace === 'file' ? { path: args.path, namespace: 'unsafe-yaml' } : undefined)
    build.onLoad({ filter: /.*/, namespace: 'unsafe-yaml' }, () => ({
      contents: `module.exports = require(${JSON.stringify(defaultSafe)});`,
      loader: 'js',
    }))
  },
}

const build = await Bun.build({
  entrypoints: [join(here, 'read-tasks.ts')],
  target: 'node',
  format: 'cjs',
  plugins: [dropUnsafeYamlSchema],
  throw: false,
})
if (!build.success) {
  for (const log of build.logs) console.error(String(log))
  throw new Error('bun build failed')
}
const entry = build.outputs.find(output => output.kind === 'entry-point')
if (!entry) throw new Error('bun build produced no entry point')
const bundle = `// backlog-workbench reader bundle; generated by reader/build.mjs. Do not edit.\n${await entry.text()}`.replace(/\s*$/, '\n')

assertBundledRequires(bundle)

const bundled = new Set()
for (const match of bundle.matchAll(/^\/\/ node_modules\/(@[^/]+\/[^/]+|[^/]+)\//gm)) bundled.add(match[1])
// mdast-util-from-markdown is imported only by the vendored write path, which the
// read-only reader tree-shakes away, so the closure is the gray-matter chain only.
for (const required of ['gray-matter', 'js-yaml']) {
  if (!bundled.has(required)) throw new Error(`Expected ${required} in the bundled closure; found ${[...bundled].join(', ')}`)
}
for (const name of bundled) {
  if (!lock.packages[`node_modules/${name}`]) throw new Error(`Bundled package ${name} is absent from package-lock.json`)
}

const licenseFileName = /^(?:licen[cs]e|copying|notice)(?:\.(?:md|markdown|txt))?$/i
const pickLicenseFile = directory => readdirSync(directory)
  .filter(name => licenseFileName.test(name))
  .sort((a, b) => a.length - b.length || a.localeCompare(b, 'en')).at(0)

const sections = []
const packageSection = name => {
  const directory = join(here, 'node_modules', name)
  const manifest = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'))
  if (manifest.name !== name) throw new Error(`Package directory ${name} holds ${manifest.name}`)
  const licenseFile = pickLicenseFile(directory)
  if (!licenseFile) throw new Error(`No license file found for bundled package ${name}; refusing to invent a notice`)
  const licenseText = readFileSync(join(directory, licenseFile), 'utf8').replace(/\s*$/, '')
  const home = manifest.homepage || manifest.repository?.url || manifest.repository || ''
  return [
    `## ${name}@${manifest.version}`,
    `License: ${manifest.license || `see ${licenseFile}`}${home ? `\nHomepage: ${home}` : ''}`,
    licenseText,
  ].join('\n\n')
}
for (const name of [...bundled].sort((a, b) => a.localeCompare(b, 'en'))) sections.push(packageSection(name))

const vendoredFiles = Object.keys(provenance.files).filter(file => file !== 'LICENSE').sort()
const notices = [
  '# Third-party notices for backlog-workbench',
  '',
  'This file is generated by reader/build.mjs from the exact dependency versions pinned in',
  'reader/package-lock.json. Do not edit it by hand; regenerate it with `cd reader && npm ci && bun run build`.',
  '',
  'The compiled reader plugin/reader.cjs contains the plugin TypeScript sources, vendored',
  'Backlog.md source files (reader/vendor), and the npm packages listed below. Each notice',
  'below is the full license text shipped inside that package at the pinned version.',
  '',
  '## Backlog.md',
  `Vendored source files from Backlog.md commit ${provenance.commit}, recorded with per-file`,
  `hashes in reader/vendor/provenance.json: ${vendoredFiles.join(', ')},`,
  'plus reader/vendor/LICENSE.',
  '',
  readFileSync(join(here, 'vendor/LICENSE'), 'utf8').replace(/\s*$/, ''),
  '',
  ...sections.flatMap(section => ['', section, '']),
  '## Build note: js-yaml unsafe schema removal',
  '',
  'The build replaces js-yaml module lib/js-yaml/schema/default_full.js with an alias of',
  'lib/js-yaml/schema/default_safe.js. gray-matter 4.0.3 parses YAML exclusively through',
  'js-yaml safeLoad and safeDump, so parsing behavior is unchanged; the removed schema is',
  'the only code path that resolved the esprima package from node_modules at startup.',
  '',
].join('\n').replace(/\n{3,}/g, '\n\n').replace(/\s*$/, '\n')

const sha256 = value => createHash('sha256').update(value).digest('hex')
const outputs = [
  [join(here, '..', 'plugin', 'reader.cjs'), bundle],
  [join(here, '..', 'plugin', 'THIRD_PARTY_NOTICES.md'), notices],
]
for (const [path, content] of outputs) {
  await Bun.write(path, content)
  console.log(`${basename(path)}: ${Buffer.byteLength(content)} bytes, sha256 ${sha256(content)}`)
}
console.log(`bundled packages (${bundled.size}): ${[...bundled].sort((a, b) => a.localeCompare(b, 'en')).join(', ')}`)
